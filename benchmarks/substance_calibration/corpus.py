"""Corpus enumeration for the substance-detector calibration harness.

Substance detectors grade the *content* of a parser's extracted markdown
along four failure classes:

* **placeholder_stubs** — `[Image omitted]`, `<figure>`, `[Table not
  extracted]`, `Col1|Col2` autogenerated headers, empty cells, LLM
  refusal stubs. Detected via curated regex + literal patterns.
* **ocr_gibberish** — character-substitution corruption, fragmented
  tokens, non-dictionary word ratio anomalies. Detected via char-class
  and word-validity statistics.
* **encoding_artifacts** — UTF-8 double-encoded mojibake, XML tag
  residue, CID font fallback markers. Extends the existing
  W_ENCODING_ARTIFACTS corpus with sub-buckets.
* **dropped_tables** — TOC/tables reduced to prose, leader-dot lines,
  numeric-heavy paragraph output where geometry says a table lived.
  Detected via geometric cross-reference (Phase 3) so most fixtures
  in this class carry a paired PDF.

Fixtures live under ``benchmarks/substance_calibration/fixtures/<class>/``.
Each fixture is a Markdown file (``*.md``) representing a parser's output
with a sibling JSON label describing expected detector behavior. Some
fixtures for the ``dropped_tables`` class additionally ship the source
PDF (`*.pdf`) so Phase 3 geometric detectors can consume it.

Ground truth JSON schema (one file per Markdown fixture)::

    {
      "document_id": "stub_form_pos1",
      "fixture_class": "placeholder_stubs",
      "is_negative": false,
      "expected_rules": ["W_PLACEHOLDER_STUB"],
      "expected_pages": [1],
      "notes": "Form with literal [Signature] and [Date] in body"
    }

Negatives (``is_negative: true``) are documents that must *not* trigger
the detector — they bound false-positive rates during calibration.
"""
from __future__ import annotations

import json
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

FixtureClass = Literal[
    "placeholder_stubs",
    "ocr_gibberish",
    "encoding_artifacts",
    "dropped_tables",
]

FIXTURE_CLASSES: tuple[FixtureClass, ...] = (
    "placeholder_stubs",
    "ocr_gibberish",
    "encoding_artifacts",
    "dropped_tables",
)

_FIXTURE_ROOT = Path(__file__).resolve().parent / "fixtures"


@dataclass(frozen=True)
class SubstanceCorpusEntry:
    """One fixture describing an expected substance-detector outcome.

    ``markdown_path`` — the parsed-markdown fixture the detector reads.
    ``source_pdf_path`` — optional; present for fixtures whose detectors
    need geometric cross-reference against the source PDF (Phase 3).
    ``expected_rules`` — rule_ids the detector should emit. Empty for
    negatives.
    """

    document_id: str
    fixture_class: FixtureClass
    markdown_path: Path
    source_pdf_path: Path | None
    is_negative: bool
    expected_rules: tuple[str, ...]
    expected_pages: tuple[int, ...]
    notes: str
    extra: dict[str, object] = field(default_factory=dict)

    @property
    def resolved(self) -> bool:
        """True when the fixture's markdown file is present on disk."""
        return self.markdown_path.exists()


def _load_ground_truth(json_path: Path) -> dict[str, object]:
    with json_path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def _entry_from_files(
    md_path: Path,
    label_path: Path,
    fixture_class: FixtureClass,
) -> SubstanceCorpusEntry:
    label = _load_ground_truth(label_path)
    pdf_field = label.get("source_pdf")
    source_pdf_path: Path | None = None
    if pdf_field:
        candidate = md_path.parent / str(pdf_field)
        source_pdf_path = candidate if candidate.exists() else None
    return SubstanceCorpusEntry(
        document_id=str(label.get("document_id") or md_path.stem),
        fixture_class=fixture_class,
        markdown_path=md_path,
        source_pdf_path=source_pdf_path,
        is_negative=bool(label.get("is_negative", False)),
        expected_rules=tuple(str(r) for r in (label.get("expected_rules") or [])),
        expected_pages=tuple(int(p) for p in (label.get("expected_pages") or [])),
        notes=str(label.get("notes", "")),
        extra={k: v for k, v in label.items() if k not in {
            "document_id", "fixture_class", "is_negative",
            "expected_rules", "expected_pages", "notes", "source_pdf",
        }},
    )


def list_fixture_class(
    fixture_class: FixtureClass,
    fixture_root: Path | None = None,
) -> list[SubstanceCorpusEntry]:
    """Enumerate all fixtures for a single class.

    Scans ``<fixture_root>/<class>/*.md`` and pairs each with the sibling
    ``*.json`` label. Fixtures without a label file are skipped silently
    (they may be work-in-progress additions).
    """
    root = fixture_root or _FIXTURE_ROOT
    directory = root / fixture_class
    if not directory.exists():
        return []
    entries: list[SubstanceCorpusEntry] = []
    for md_path in sorted(directory.glob("*.md")):
        label_path = md_path.with_suffix(".json")
        if not label_path.exists():
            continue
        entries.append(_entry_from_files(md_path, label_path, fixture_class))
    return entries


def iter_substance_corpus(
    fixture_root: Path | None = None,
) -> Iterable[SubstanceCorpusEntry]:
    """Yield every fixture across every class.

    Order is stable: classes iterated in ``FIXTURE_CLASSES`` order, then
    alphabetically within each class.
    """
    for cls in FIXTURE_CLASSES:
        yield from list_fixture_class(cls, fixture_root=fixture_root)


def fixture_class_dir(fixture_class: FixtureClass) -> Path:
    """Return the on-disk directory for a fixture class (may not exist)."""
    return _FIXTURE_ROOT / fixture_class
