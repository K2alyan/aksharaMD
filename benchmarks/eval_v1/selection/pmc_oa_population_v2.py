"""PMC-OA rank-walk under Selection Algorithm V2.

Extends the V1 rank-walk (:mod:`benchmarks.eval_v1.selection.pmc_oa_population`)
by adding a second eligibility gate: after V1 metadata filters pass,
the walker fetches JATS and applies
:func:`apply_text_oracle_filters` — the predicate defined in
:mod:`benchmarks.eval_v1.selection.pmc_oa_text_oracle_eligibility`.

Every candidate that reaches the JATS-fetch step is contaminated for
held-out purposes and is recorded verbatim in the inspection ledger
(with its JATS SHA-256 and the V2 decision) so audit records
distinguish V2-inspected candidates from those short-circuited by the
V1 metadata gate. The V1 exclusion ledger is NOT modified by this
walk — its inputs remain identical to what V1 saw. Contamination
generated by the V2 inspection lives in the V2 inspection ledger
alone.

Fail-closed on network exhaustion: if metadata or JATS retrieval
exhausts its retry budget the run STOPS. It never converts a
transient network condition into a document-level ineligibility
verdict.
"""
from __future__ import annotations

import hashlib
import urllib.parse
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any

from benchmarks.eval_v1.acquisition.pmc_oa_aws import (
    BUCKET_HTTPS,
    PmcVersionMetadata,
    apply_metadata_filters,
    http_get_pmc,
    jats_pmcid_matches,
)
from benchmarks.eval_v1.corpus_split import Partition, assign_partition
from benchmarks.eval_v1.selection.pilot_selector import (
    Candidate,
    _rank,
    make_candidate,
)
from benchmarks.eval_v1.selection.pmc_oa_population import (
    _fetch_metadata_with_policy,
)
from benchmarks.eval_v1.selection.pmc_oa_text_oracle_eligibility import (
    PMC_MIN_BODY_TOKENS,
    PMC_TEXT_ORACLE_ELIGIBILITY_VERSION,
    apply_text_oracle_filters,
)

# Re-exported for convenience so the V2 driver can attach these to the
# emitted V2 manifest without importing from the eligibility module.
__pmc_min_body_tokens__ = PMC_MIN_BODY_TOKENS
__pmc_text_oracle_eligibility_version__ = PMC_TEXT_ORACLE_ELIGIBILITY_VERSION


def _now_utc() -> str:
    return datetime.now(tz=UTC).isoformat(timespec="seconds")


def _default_fetch_jats(md: PmcVersionMetadata) -> tuple[bytes, str]:
    """Fetch canonical JATS bytes for the exact PMCID/version.

    Uses the pinned S3 URL structure the acquisition layer already
    validated. Returns ``(raw_bytes, sha256)``; the caller records
    both in the inspection ledger. Network policy (retry, pacing,
    ``NetworkExhaustionError``) is inherited from
    :func:`http_get_pmc`.
    """
    url = BUCKET_HTTPS + urllib.parse.quote(md.object_key("xml"), safe="/")
    body, _headers = http_get_pmc(url)
    return body, hashlib.sha256(body).hexdigest()


@dataclass(frozen=True)
class V2InspectionRecord:
    """One row of the V2 selection inspection ledger.

    Records a candidate that reached the JATS-fetch step regardless
    of its V2 decision. Every entry represents development
    contamination: the article's JATS was pulled and inspected during
    selection.
    """

    canonical_id: str
    pmcid: str
    version: int
    rank_key: str
    jats_sha256: str
    decision_ok: bool
    decision_reason: str | None
    inspected_utc: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "canonical_id": self.canonical_id,
            "pmcid": self.pmcid,
            "version": self.version,
            "rank_key": self.rank_key,
            "jats_sha256": self.jats_sha256,
            "decision_ok": self.decision_ok,
            "decision_reason": self.decision_reason,
            "inspected_utc": self.inspected_utc,
            "usage": (
                "B1a-5a-V2 PMC textual-oracle eligibility inspection "
                "(JATS bytes fetched during selection)"
            ),
            "evaluation_eligibility": "development_only",
            "held_out_v1_eligible": False,
        }


@dataclass
class V2RankWalkResult:
    """Outcome of one V2 rank-walk over the pinned PMC inventory."""

    dev_assignment_count_before_metadata_eligibility: int
    excluded_before_rank_walk: int
    metadata_records_probed: int
    jats_candidates_fetched: int
    eligible_records_found_before_stop: int
    stopping_rule: str
    rejection_counts_by_reason: dict[str, int] = field(default_factory=dict)
    inspection_ledger: list[V2InspectionRecord] = field(default_factory=list)
    ineligible_head: list[dict[str, Any]] = field(default_factory=list)


def rank_walk_v2_eligible_dev(
    pmcid_to_latest: dict[str, int],
    excluded_ids: set[str],
    *,
    stop_after_eligible: int = 12,
    on_progress: Callable[[int, int, int], None] | None = None,
    fetch_metadata: Callable[
        [str], tuple[PmcVersionMetadata, bytes, str],
    ] = _fetch_metadata_with_policy,
    fetch_jats: Callable[[PmcVersionMetadata], tuple[bytes, str]] = _default_fetch_jats,
) -> tuple[list[Candidate], V2RankWalkResult]:
    """PMC rank-walk under Selection Algorithm V2.

    Sequence per candidate (in SHA-256(canonical_id) rank order):

    1. Fetch metadata JSON.
    2. Apply V1 :func:`apply_metadata_filters`. If reject, record and
       continue — no JATS fetch.
    3. Fetch JATS bytes and hash them.
    4. Validate JATS-internal PMCID matches the canonical id
       (identity gate). If mismatch, record and continue — but the
       inspection ledger still logs the JATS SHA because the JATS
       was fetched.
    5. Apply :func:`apply_text_oracle_filters` — the same predicate
       reviewed and merged in PR #186. Record the decision.
    6. If V2-eligible, add to the eligible list. Stop after
       ``stop_after_eligible`` are found.

    Network semantics: ``NetworkExhaustionError`` raised by
    ``fetch_metadata`` or ``fetch_jats`` propagates unchanged. The
    caller is responsible for STOPPING the run. A transient network
    condition must never be silently converted to a document-level
    ineligibility.
    """
    # ---- DEV assignment + exclusion removal + rank ordering
    dev_ids_pre_exclusion: list[str] = []
    for pmcid, version in pmcid_to_latest.items():
        canonical = f"{pmcid}.{version}"
        if assign_partition(canonical) is Partition.DEV:
            dev_ids_pre_exclusion.append(canonical)
    dev_assignment_count = len(dev_ids_pre_exclusion)
    excluded = [cid for cid in dev_ids_pre_exclusion if cid in excluded_ids]
    remaining = [cid for cid in dev_ids_pre_exclusion if cid not in excluded_ids]
    remaining.sort(key=_rank)

    eligible: list[Candidate] = []
    inspection_ledger: list[V2InspectionRecord] = []
    rejection_counts: dict[str, int] = {}
    ineligible: list[dict[str, Any]] = []
    metadata_probed = 0
    jats_fetched = 0

    def _bump(reason: str) -> None:
        rejection_counts[reason] = rejection_counts.get(reason, 0) + 1

    for canonical in remaining:
        if len(eligible) >= stop_after_eligible:
            break
        metadata_probed += 1
        if on_progress and metadata_probed % 5 == 0:
            on_progress(metadata_probed, jats_fetched, len(eligible))

        # Step 1: metadata. NetworkExhaustionError propagates.
        md, _md_raw, _md_sha = fetch_metadata(canonical)

        # Step 2: V1 metadata filter.
        md_decision = apply_metadata_filters(md)
        if not md_decision.ok:
            reason = md_decision.reason or "metadata_ineligible"
            _bump(reason)
            if len(ineligible) < 200:
                ineligible.append({
                    "canonical_id": canonical, "stage": "metadata", "reason": reason,
                })
            continue

        # Step 3: JATS. NetworkExhaustionError propagates.
        jats_bytes, jats_sha = fetch_jats(md)
        jats_fetched += 1

        pmcid = canonical.rsplit(".", 1)[0]
        version = int(canonical.rsplit(".", 1)[1])
        rank_key = _rank(canonical)

        # Step 4: JATS PMCID identity check.
        matches, got = jats_pmcid_matches(jats_bytes, md.pmcid)
        if not matches:
            reason = f"jats_pmcid_mismatch:got={got!r}"
            _bump(reason)
            inspection_ledger.append(V2InspectionRecord(
                canonical_id=canonical, pmcid=pmcid, version=version,
                rank_key=rank_key, jats_sha256=jats_sha,
                decision_ok=False, decision_reason=reason,
                inspected_utc=_now_utc(),
            ))
            if len(ineligible) < 200:
                ineligible.append({
                    "canonical_id": canonical, "stage": "jats_identity",
                    "reason": reason,
                })
            continue

        # Step 5: V2 predicate.
        v2 = apply_text_oracle_filters(md, jats_bytes)
        inspection_ledger.append(V2InspectionRecord(
            canonical_id=canonical, pmcid=pmcid, version=version,
            rank_key=rank_key, jats_sha256=jats_sha,
            decision_ok=v2.ok, decision_reason=v2.reason,
            inspected_utc=_now_utc(),
        ))
        if not v2.ok:
            reason = v2.reason or "text_oracle_reject"
            _bump(reason)
            if len(ineligible) < 200:
                ineligible.append({
                    "canonical_id": canonical, "stage": "v2_oracle", "reason": reason,
                })
            continue

        # Step 6: V2-eligible.
        eligible.append(make_candidate(
            canonical_id=canonical,
            metadata={
                "pmcid": pmcid,
                "version": version,
                "license_code": md.license_code,
                "title": md.title[:120] if md.title else None,
                "pmid": md.pmid,
                "citation": md.citation,
                "jats_sha256": jats_sha,
            },
            corpus="pmc_oa",
        ))

    result = V2RankWalkResult(
        dev_assignment_count_before_metadata_eligibility=dev_assignment_count,
        excluded_before_rank_walk=len(excluded),
        metadata_records_probed=metadata_probed,
        jats_candidates_fetched=jats_fetched,
        eligible_records_found_before_stop=len(eligible),
        stopping_rule=f"stop after {stop_after_eligible} eligible V2 DEV candidates",
        rejection_counts_by_reason=rejection_counts,
        inspection_ledger=inspection_ledger,
        ineligible_head=ineligible,
    )
    return eligible, result


